"""
Изучите и напишите алгоритм сортировки, но не пузырьковой, сортировки вставками или сортировки слиянием.

Пирамидальная сортировка (heap sort) — это алгоритм сортировки, основанный на структуре данных куча (heap), 
чаще всего двоичной куче (binary heap). Алгоритм работает, сначала перестраивая массив в max-heap (макс-кучу) — такую кучу, 
где каждый родитель больше своих потомков, а затем последовательно извлекает максимальный элемент из вершины кучи 
и помещает его в конец массива, уменьшая размер кучи. Это обеспечивает сортировку массива по возрастанию.

Основные термины:

Heap — куча, структура данных в виде дерева с особыми свойствами;

Heapify — операция поддержания свойства кучи для поддерева;

Root — корень дерева или кучи;

Parent — родительский узел;

Child — дочерний узел;

Max-Heap — макс-куча, в которой у каждого узла значение больше или равно значениям потомков;

Min-Heap — мин-куча, противоположность макс-кучи.
"""

def heapify(arr, n, i):
    largest = i  # Инициализируем наибольший элемент как корень
    left = 2 * i + 1  # Левый дочерний узел
    right = 2 * i + 2  # Правый дочерний узел

    if left < n and arr[left] > arr[largest]:
        largest = left

    if right < n and arr[right] > arr[largest]:
        largest = right

    if largest != i:
        arr[i], arr[largest] = arr[largest], arr[i]  # Обмен
        heapify(arr, n, largest)  # Рекурсивный вызов heapify для затронутого поддерева

def heap_sort(arr):
    n = len(arr)

    # Построение макс-кучи
    for i in range(n // 2 - 1, -1, -1):
        heapify(arr, n, i)

    # Извлечение элементов из кучи один за другим
    for i in range(n - 1, 0, -1):
        arr[i], arr[0] = arr[0], arr[i]  # Обмен корня и последнего элемента
        heapify(arr, i, 0)  # Поддержание свойства кучи для уменьшенной кучи

# Пример использования
array = [12, 11, 13, 5, 6, 7]
heap_sort(array)
print("Отсортированный массив:", array)

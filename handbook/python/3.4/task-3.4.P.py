"""
Виталий любит играть в карты. Он решил выяснить, какие есть вариации вытащить из колоды определённые тройки карт. 
Напишите программу, которая выводит список подходящих троек в лексикографическом порядке с учётом заданных условий.

Формат ввода
В первой строке записана масть, которая должна присутствовать в тройке.
Во второй строке записан достоинство, которого не должно быть в тройке.

Формат вывода
Выведите на экран первые 10 получившихся троек.
Карты в каждой комбинации должны быть отсортированы лексикографически (по строке названия карты). Карты комбинации выводятся через запятую с пробелом после неё.
Комбинации между собой также должны быть отсортированы в лексикографическом порядке по строке, представляющей комбинацию целиком.

Примечание
Обратите внимание: валет-дама-король-туз лексикографически упорядочены. Но «10 ...» лексикографически младше, чем «2 ...», а бубны младше, чем пики.

Масти в именительном и родительном падежах:

Именительный	Родительный
буби	бубен
пики	пик
трефы	треф
черви	червей

Подсказка
Возьмите за основу решение задачи F.

Используя итератор combinations, переберите все возможные тройки карт, исключив излишние согласно условию.

Прекратите обработку комбинаций по накоплению 10 строк.

Пример 1
Ввод

пики
10
Вывод

2 бубен, 2 пик, 2 треф
2 бубен, 2 пик, 2 червей
2 бубен, 2 пик, 3 бубен
2 бубен, 2 пик, 3 пик
2 бубен, 2 пик, 3 треф
2 бубен, 2 пик, 3 червей
2 бубен, 2 пик, 4 бубен
2 бубен, 2 пик, 4 пик
2 бубен, 2 пик, 4 треф
2 бубен, 2 пик, 4 червей
Пример 2
Ввод

трефы
король
Вывод

10 бубен, 10 пик, 10 треф
10 бубен, 10 пик, 2 треф
10 бубен, 10 пик, 3 треф
10 бубен, 10 пик, 4 треф
10 бубен, 10 пик, 5 треф
10 бубен, 10 пик, 6 треф
10 бубен, 10 пик, 7 треф
10 бубен, 10 пик, 8 треф
10 бубен, 10 пик, 9 треф
10 бубен, 10 пик, валет треф
"""

from itertools import combinations

try:
	required_suit = input().strip()
except EOFError:
	required_suit = ""

try:
	forbidden_rank = input().strip()
except EOFError:
	forbidden_rank = ""

# Номинатив -> родительный (для вывода)
suit_genitive = {
	'буби': 'бубен',
	'пики': 'пик',
	'трефы': 'треф',
	'черви': 'червей',
}

ranks = [str(i) for i in range(2, 11)] + ['валет', 'дама', 'король', 'туз']
suits_nom = ['буби', 'пики', 'трефы', 'черви']

# Составим список карт в виде (card_str, suit_nom, rank)
deck = []
for r in ranks:
	for s in suits_nom:
		card_str = f"{r} {suit_genitive[s]}"
		deck.append((card_str, s, r))
# Отсортируем колоду лексикографически по строковому представлению карты
deck.sort(key=lambda x: x[0])

results = []

# Перебираем все тройки (в лексикографическом порядке)
for combo in combinations(deck, 3):
	# проверить, что хотя бы одна карта нужной масти (в именительном) присутствует
	suits_in_combo = {c[1] for c in combo}
	if required_suit not in suits_in_combo:
		continue

	# исключить комбинации, содержащие запрещённое достоинство
	ranks_in_combo = {c[2] for c in combo}
	if forbidden_rank in ranks_in_combo:
		continue

	# внутри комбинации карты должны быть лексикографически отсортированы по card_str
	card_strs = sorted(c[0] for c in combo)
	combo_str = ', '.join(card_strs)
	results.append(combo_str)

	# остановка по накоплению 10 строк (коллекция уже в лексикографическом порядке)
	if len(results) >= 10:
		break

for line in results:
	print(line)


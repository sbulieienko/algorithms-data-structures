"""
Давайте вновь поможем Виталию — теперь его интересует, какой вариант расклада идёт сразу после уже полученного.
Напишите программу, которая находит следующий подходящий вариант тройки карт, соответствующий условиям.

Формат ввода
В первой строке записана масть, которая должна присутствовать в тройке.
Во второй строке записан достоинство, которого не должно быть в тройке.
В третьей строке записан предыдущий вариант полученный Виталием.

Формат вывода
Выведите следующий вариант расклада.

Примечание
Обратите внимание: валет-дама-король-туз лексикографически упорядочены. Но «10 ...» лексикографически младше, чем «2 ...», а бубны младше, чем пики.

Масти в именительном и родительном падежах:

Именительный	Родительный
буби	бубен
пики	пик
трефы	треф
черви	червей

Подсказа
Используйте решение предыдущей задачи и производите перебор пока не получите вариант Виталия.

Пример 1
Ввод:
пики
10
9 пик, король треф, туз червей

Вывод:
9 пик, король червей, туз бубен

Пример 2
Ввод:
трефы
король
2 червей, туз пик, туз треф

Вывод:
2 червей, туз треф, туз червей
"""

from itertools import combinations

try:
	required_suit = input().strip()
except EOFError:
	required_suit = ""

try:
	forbidden_rank = input().strip()
except EOFError:
	forbidden_rank = ""

try:
	previous_combo = input().strip()
except EOFError:
	previous_combo = ""

# Номинатив -> родительный (для вывода)
suit_genitive = {
	'буби': 'бубен',
	'пики': 'пик',
	'трефы': 'треф',
	'черви': 'червей',
}

ranks = [str(i) for i in range(2, 11)] + ['валет', 'дама', 'король', 'туз']
suits_nom = ['буби', 'пики', 'трефы', 'черви']

# Составим список карт в виде (card_str, suit_nom, rank)
deck = []
for r in ranks:
	for s in suits_nom:
		card_str = f"{r} {suit_genitive[s]}"
		deck.append((card_str, s, r))
# Отсортируем колоду лексикографически по строковому представлению карты
deck.sort(key=lambda x: x[0])

find = False

# Перебираем все тройки (в лексикографическом порядке)
for combo in combinations(deck, 3):
	# проверить, что хотя бы одна карта нужной масти (в именительном) присутствует
	suits_in_combo = {c[1] for c in combo}
	if required_suit not in suits_in_combo:
		continue

	# исключить комбинации, содержащие запрещённое достоинство
	ranks_in_combo = {c[2] for c in combo}
	if forbidden_rank in ranks_in_combo:
		continue

	# внутри комбинации карты должны быть лексикографически отсортированы по card_str
	card_strs = sorted(c[0] for c in combo)
	combo_str = ', '.join(card_strs)

	# печать следующего варианта
	if find:
		print(combo_str)
		break	
	
	# проверка предыдущего варианта
	if combo_str == previous_combo:
		find = True


"""
Что нужно сделать
Ваша задача — проанализировать вовлечённость ученика и вычислить его рейтинг. А если входные данные окажутся неверными — указать это.

Формат ввода
Одна строчка, в которой через пробел подаются следующие данные:


N M Q cw sw hw tw
N (num_students) — число учеников на курсе
M (num_lessons) — количество занятий в курсе
Q (max_rating) — максимальный рейтинг
cw (classwork_coefficient) — коэффициент для активности на занятии
sw (selfwork_coefficient) — коэффициент для практики
hw (homework_coefficient) — коэффициент для домашней работы
tw (testwork_coefficient) — коэффициент для контрольной работы

Далее идёт фамилия ученика и несколько строчек (M) с оценками ученика на занятиях в формате:


Иванов
a₁,b₁,c₁,d₁  
a₂,b₂,c₂,d₂  
a₃,b₃,c₃,d₃  
⋮  
aₘ,bₘ,cₘ,dₘ
Где aᵢ,bᵢ,cᵢ,dᵢ — это оценки за i-ое занятие:

aᵢ (classwork_grade) — оценка за активность на занятии
bᵢ (selfwork_grade) — оценка за практику на занятии
cᵢ (homework_grade) — оценка за домашнюю работу на занятии
dᵢ (testwork_grade) — оценка за контрольную работу на занятии

Если не было активности, ученик отсутствовал либо не проявил себя на занятии — значение за активность будет 0.

Формат вывода
Фамилия и процент от максимального рейтинга, округленный до целого числа с помощью функции round(). Через пробел.


Иванов x%
Также сделайте проверку на верность вводных данных. Если условие не выполняется, то необходимо вывести строку «Во введённых данных ошибка»

M > 0 (количество проведённых занятий равно 1 и больше)
cw, sw, hm, tw > 0 (все активности учитываются в рейтинге)
Рассчитанный максимальный рейтинг ученика на программе не должен превышать Q.

Во введённых данных ошибка


Формула для расчёта рейтинга

Рейтинг ученика = Сумма баллов по всем занятиям

Баллы за одно занятие = (
Оценка за активность • Коэффициент за активность
+ Оценка за практику • Коэффициент за практику
+ Оценка за домашнюю работу • Коэффициент за домашнюю работу
+ Оценка за контрольную работу • Коэффициент за контрольную работу
)


Для примера возьмём следующие входные данные:


4 5 190 1 2 4 6
Иванов
2,3,0,0
0,4,0,1
0,0,9,0
0,3,0,0
4,0,0,2
У Иванова пять занятий и на каждом занятии он получал оценки за разные активности. 
По входным данным вы знаете, что коэффициенты для каждого типа занятий следующие:

Название активности	Коэффициент
Активность на занятии	1
Практика	2
Домашняя работа	4
Контрольная	6

Теперь нужно пройтись по каждому занятию, посчитать сколько баллов он за них получил. И просуммировать их.

Занятие	Количество баллов рейтинга
1	2 • 1 + 3 • 2 + 0 • 4 + 0 • 6 = 8
2	0 • 1 + 4 • 2 + 0 • 4 + 1 • 6 = 14
3	0 • 1 + 0 • 2 + 9 • 4 + 0 • 6 = 36
4	0 • 1 + 3 • 2 + 0 • 4 + 0 • 6 = 6
5	4 • 1 + 0 • 2 + 0 • 4 + 2 • 6 = 16
Итого	80

"""
data = list(map(int, input().split()))
num_students = data[0]
num_lessons = data[1] 
max_rating = data[2]
classwork_coefficient = data[3]
selfwork_coefficient = data[4]
homework_coefficient = data[5]
testwork_coefficient = data[6]

if num_lessons <= 0 or classwork_coefficient <= 0 or selfwork_coefficient <= 0:
    print("Во введённых данных ошибка")
    exit()  

if homework_coefficient <= 0 or testwork_coefficient <= 0:
    print("Во введённых данных ошибка")
    exit()  
    
student_name = input()
total_rating = 0
for _ in range(num_lessons):
    grades = list(map(int, input().split(',')))
    classwork_grade = grades[0]
    selfwork_grade = grades[1]
    homework_grade = grades[2]
    testwork_grade = grades[3]
    
    lesson_rating = (classwork_grade * classwork_coefficient +
                     selfwork_grade * selfwork_coefficient +
                     homework_grade * homework_coefficient +
                     testwork_grade * testwork_coefficient)
    total_rating += lesson_rating

if total_rating > max_rating:
    print("Во введённых данных ошибка")
else:
    percentage = round((total_rating / max_rating) * 100)
    print(f"{student_name} {percentage}%")


"""
Средний рост

Учитель физкультуры задался вопросом, на сколько в среднем его подопечные выросли за прошедший месяц.
Поможем ему провести вычисления на Python!

Напишите программу, которая определяет, на сколько изменился средний рост учеников в классе.

Формат ввода
Вводится информация о детях в формате:
<Имя> <Рост месяц назад> <Рост сейчас>

Формат вывода
Одно число — ответ на вопрос задачи.
Ответ округлите до целых. Например, функцией round.


Подсказка
Организуйте цикл по стандартному потоку ввода и преобразуйте введённые данные в два списка:

список чисел месячной давности;
список актуальных чисел.
Вычислите средние значения для каждого из списков и выведите их разность.

Пример 1
Ввод

Аня 160 162
Боря 165 172
Вова 165 165
Вывод

3
Пример 2
Ввод

Аня 161 165
Боря 167 172
Вова 165 166
Дима 173 178
Вывод

4
"""
from sys import stdin

old_heights = []
new_heights = []

for line in stdin:
    parts = line.strip().split()
    if len(parts) == 3:
        name, old_height, new_height = parts
        try:
            old_heights.append(int(old_height))
            new_heights.append(int(new_height))
        except ValueError:
            continue

if old_heights and new_heights:
    avg_old = sum(old_heights) / len(old_heights)
    avg_new = sum(new_heights) / len(new_heights)
    print(round(avg_new - avg_old))
